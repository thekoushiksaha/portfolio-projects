CREATE TABLE roles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    role_id         BIGINT NOT NULL REFERENCES roles (id),
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    updated_at      TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE expenses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (id),
    amount          NUMERIC(12, 2) NOT NULL,
    category        VARCHAR(255) NOT NULL,
    expense_date    DATE NOT NULL,
    note            VARCHAR(255),
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT expenses_category_check
        CHECK (category IN ('FOOD','TRANSPORT', 'BILLS', 'SHOPPING', 'HEALTH', 'OTHER'))
);

CREATE INDEX idx_expense_user_date ON expenses (user_id, expense_date);

CREATE TABLE spending_limits (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (id),
    category        VARCHAR(255),
    monthly_limit   NUMERIC(12, 2) NOT NULL,
    CONSTRAINT  spending_limits_category_check
        CHECK (category IN ('FOOD', 'TRANSPORT', 'BILLS', 'SHOPPING', 'HEALTH', 'OTHER')),
    CONSTRAINT uk_spending_limits_user_category UNIQUE (user_id, category)
);

-- A null category means "Overall monthly limit". Plain UNIQUE treats NULLs as different,
-- so this partial index guarentees one overall limit per user.
CREATE UNIQUE INDEX uq_one_overall_limit ON spending_limits (user_id) WHERE category IS NULL;

CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token           VARCHAR(255) NOT NULL UNIQUE,
    user_id         BIGINT NOT NULL REFERENCES users (id),
    expiry_date     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked         BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE contact_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE
);